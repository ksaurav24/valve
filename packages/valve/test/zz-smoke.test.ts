import { expect, it } from 'vitest';
import { createValve, memoryStore } from '../src/index.js';
it('smoke', async () => {
  let now = 1000;
  const store = memoryStore({ clock: () => now });
  const rate = [{ name: 'tp', limit: 10, interval: 1000, burst: 10 }];
  const a = createValve({ id: 'x', rate, store, limits: 'managed' });
  const b = createValve({ id: 'x', rate: [{ name: 'tp', limit: 99, interval: 1000, burst: 10 }], store, limits: 'managed' });
  const events: unknown[] = [];
  b.on('limits', (e) => events.push(e.version));
  b.on('warning', (e) => events.push(e.message));
  for (let i = 0; i < 10; i++) await a.run(() => i);
  const r = await a.getLimits();
  expect(r.revision).toBe(1);
  const u = await a.updateLimits({ tp: { limit: 20 } });
  expect(u.revision).toBe(2);
  expect(u.rules.tp).toEqual({ algorithm: 'gcra', intervalMs: 1000, limit: 20, burst: 10 });
  const req = { id: 'x', rules: [{ name: 'tp', algorithm: 'gcra' as const, limit: 10, intervalMs: 1000, burst: 10, key: 'named:tp' }], costs: [1] };
  expect(store.managed!.acquireSync!(req).retryAfterMs).toBe(50);
  now += 50;
  expect(store.managed!.acquireSync!(req).granted).toBe(1);
  now += 1000; await b.run(() => 1);
  console.log(events);
  expect((await a.updateLimits({ tp: { limit: 20 } })).version).toBe(u.version);
});
